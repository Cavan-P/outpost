export type EndgameGoal =
  | 'mate' // deliver checkmate
  | 'promote' // queen a pawn (the rest is technique)
  | 'win' // checkmate, or strip the opponent to a bare king while keeping a major piece
  | 'draw' // hold: reach a draw, eliminate the last pawn, or survive `holdMoves` moves

export interface EndgameDef {
  id: string // ids starting with "mate-" count toward the Mate Artist achievement
  name: string
  category: 'Checkmates' | 'Pawn endings' | 'Rook endings' | 'Minor pieces' | 'Queen endings'
  fen: string
  side: 'w' | 'b' // the side you play
  goal: EndgameGoal
  holdMoves?: number // for draw goals: surviving this many of your moves counts as holding
  level: 'Essential' | 'Intermediate' | 'Advanced'
  summary: string
  technique: string[]
}

